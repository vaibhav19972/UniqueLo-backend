/**
 * razorpay-create-order — creates a Razorpay order for a priced cart.
 *
 * THE RULE THIS FUNCTION ENFORCES: it never accepts an amount from the browser.
 * The cart goes in, `quote_order()` prices it, and *that* number is charged. A
 * client-supplied amount would let anyone buy a ₹1,899 scarf for ₹1 — and the
 * repo already refuses client-supplied money everywhere else (`pricing.ts`
 * computes nothing).
 *
 * `total_cents` is passed straight to Razorpay as `amount`. No multiplication, no
 * division: this codebase's `*_cents` ARE paise (formatPrice divides by 100), and
 * Razorpay's `amount` is paise. Converting would charge 100× or 1/100×.
 *
 * WHY IT PERSISTS THE FULL LINE, NOT JUST sku+qty
 * -----------------------------------------------
 * `verify` must hand `payment_intents.items` to `place_order` untouched — it may
 * never rebuild a cart from what the browser re-submits. And `place_order` writes
 * `product_name`, `color`, `size` into `order_items`. Fed only `{variant_sku,
 * quantity}` it does not fail: it was hardened (20261101) to coalesce those to
 * 'Embroidered Garment' / 'Standard' / 'M'. The order would succeed and every
 * confirmation email would name a product the customer did not buy, in a size
 * they do not wear. So the full line is captured here, where it is still known.
 *
 * Deno runtime. Secrets come from `Deno.env` — never from the bundle.
 */

import { createClient } from 'npm:@supabase/supabase-js@2';
import {
  CORS_HEADERS,
  createRazorpayOrder,
  json,
  RazorpayApiError,
} from '../_shared/razorpay.ts';

/** What the client sends: whichever casing it likes. Normalised below. */
interface RawLine {
  id?: string;
  productSlug?: string;
  product_slug?: string;
  variantSku?: string;
  variant_sku?: string;
  productName?: string;
  product_name?: string;
  color?: string;
  size?: string;
  quantity?: number;
  customization?: unknown;
}

interface RequestBody {
  items: RawLine[];
  coupon_code?: string | null;
  customer_email?: string | null;
  customer_name?: string | null;
  customer_phone?: string | null;
  shipping_address?: unknown;
  /** The UUID place_order will write as orders.id. Generated by the client. */
  client_order_id: string;
}

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** The exact shape place_order's `jsonb_to_recordset` declares. */
interface OrderItem {
  id: string;
  product_slug: string;
  variant_sku: string;
  product_name: string;
  color: string;
  size: string;
  quantity: number;
  customization: unknown;
}

Deno.serve(async (req: Request): Promise<Response> => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: CORS_HEADERS });
  if (req.method !== 'POST') return json({ error: 'Method not allowed' }, 405);

  const keyId = Deno.env.get('RAZORPAY_KEY_ID');
  const keySecret = Deno.env.get('RAZORPAY_KEY_SECRET');
  const supabaseUrl = Deno.env.get('SUPABASE_URL');
  const serviceKey = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY');

  if (!keyId || !keySecret) {
    // An operator error, not a customer error. Name it as one.
    return json({ error: 'Payment gateway is not configured. Please use Cash on delivery.' }, 503);
  }
  if (!supabaseUrl || !serviceKey) {
    return json({ error: 'Server is misconfigured.' }, 503);
  }

  let body: RequestBody;
  try {
    body = await req.json();
  } catch {
    return json({ error: 'Invalid JSON body.' }, 400);
  }

  // ── Normalise the cart into the shape place_order writes ──────────────
  if (!Array.isArray(body.items) || body.items.length === 0) {
    return json({ error: 'A bag needs at least one item.' }, 400);
  }

  const items: OrderItem[] = [];
  for (const raw of body.items) {
    const sku = (raw.variantSku ?? raw.variant_sku ?? '').trim();
    if (!sku) continue;
    items.push({
      // Stable per line so a retried verify re-inserts identical ids rather than
      // colliding on regenerated ones.
      id: raw.id && UUID_RE.test(raw.id) ? raw.id : crypto.randomUUID(),
      product_slug: (raw.productSlug ?? raw.product_slug ?? '').trim(),
      variant_sku: sku,
      product_name: (raw.productName ?? raw.product_name ?? '').trim(),
      color: (raw.color ?? '').trim(),
      size: (raw.size ?? '').trim(),
      quantity: Math.max(1, Math.trunc(Number(raw.quantity) || 1)),
      customization: raw.customization ?? null,
    });
  }
  if (items.length === 0) return json({ error: 'No valid items in the bag.' }, 400);

  if (!body.client_order_id || !UUID_RE.test(body.client_order_id)) {
    return json({ error: 'client_order_id must be a UUID.' }, 400);
  }
  const email = (body.customer_email ?? '').trim().toLowerCase();
  if (!email) return json({ error: 'An email is required to create a payment.' }, 400);

  const clientOrderId = body.client_order_id;
  const couponCode = (body.coupon_code ?? '').trim().toUpperCase() || null;

  const admin = createClient(supabaseUrl, serviceKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  });

  // ── Price server-side ─────────────────────────────────────────────────
  // A projection, not the stored shape: price_cart declares only these two and
  // reads nothing else, so passing the full objects would work but would imply a
  // contract it does not have. Money is decided by quote_order alone.
  const { data: quote, error: quoteError } = await admin.rpc('quote_order', {
    p_items: items.map((i) => ({ variant_sku: i.variant_sku, quantity: i.quantity })),
    p_coupon_code: couponCode,
    p_customer_email: email,
    p_payment_method: 'prepaid',
  });

  if (quoteError) {
    // Business errors (unknown SKU P0002, no shipping rule P0003) are the
    // customer's to fix, so they surface verbatim.
    return json({ error: quoteError.message || 'Could not price this bag.' }, 400);
  }
  if (!quote) return json({ error: 'Server returned an empty quote.' }, 502);
  if (quote.coupon?.error) return json({ error: quote.coupon.error }, 400);

  const amount: number = quote.total_cents;
  if (!Number.isInteger(amount) || amount < 100) {
    return json({ error: `Order total must be at least 100 paise (got ${amount}).` }, 400);
  }

  // ── Idempotency ───────────────────────────────────────────────────────
  // A double-click must not mint two Razorpay orders for one cart. Reuse the live
  // intent when the price has not moved; retire it if it has.
  const { data: existing } = await admin
    .from('payment_intents')
    .select('id, provider_order_id, amount_cents, status')
    .eq('client_order_id', clientOrderId)
    .eq('status', 'created')
    .not('provider_order_id', 'is', null)
    .order('created_at', { ascending: false })
    .limit(1)
    .maybeSingle();

  if (existing && existing.amount_cents === amount && existing.provider_order_id) {
    return json({
      razorpay_order_id: existing.provider_order_id,
      amount: existing.amount_cents,
      currency: 'INR',
      key_id: keyId,
      reused: true,
    });
  }
  if (existing) {
    // Price moved since the intent was made. The old Razorpay order is now
    // chargeable for a wrong amount, so retire it explicitly.
    await admin
      .from('payment_intents')
      .update({ status: 'expired', failure_reason: 'superseded by re-priced quote' })
      .eq('id', existing.id);
  }

  // ── Create the Razorpay order ─────────────────────────────────────────
  let rzp;
  try {
    rzp = await createRazorpayOrder(
      {
        amountCents: amount,
        // Razorpay caps receipt at 40 chars; a dashed UUID is 36.
        receipt: clientOrderId,
        notes: { client_order_id: clientOrderId, customer_email: email },
      },
      keyId,
      keySecret
    );
  } catch (err) {
    const status = err instanceof RazorpayApiError ? err.status : 502;
    // A 401 from Razorpay means OUR key pair is wrong or revoked. Never let that
    // read as a declined card — 502 puts the fault on the server where it belongs.
    const message =
      status === 401
        ? 'The payment gateway rejected our credentials. Please use Cash on delivery.'
        : err instanceof Error
          ? err.message
          : 'Could not reach the payment gateway.';
    return json({ error: message }, 502);
  }

  const { error: insertError } = await admin.from('payment_intents').insert({
    provider: 'razorpay',
    client_order_id: clientOrderId,
    provider_order_id: rzp.id,
    amount_cents: amount,
    currency: rzp.currency ?? 'INR',
    status: 'created',
    customer_email: email,
    customer_name: (body.customer_name ?? '').trim() || null,
    customer_phone: (body.customer_phone ?? '').trim() || null,
    shipping_address: body.shipping_address ?? null,
    coupon_code: couponCode,
    items,
  });

  if (insertError) {
    // The Razorpay order exists but we cannot record it. Refuse rather than hand
    // out an order id we could never reconcile.
    return json({ error: 'Could not record this payment attempt. Please retry.' }, 500);
  }

  // The secret is not in this response and never will be.
  return json({
    razorpay_order_id: rzp.id,
    amount,
    currency: rzp.currency ?? 'INR',
    key_id: keyId,
    client_order_id: clientOrderId,
  });
});
